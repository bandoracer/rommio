    @Test
    fun lightsMatchTheStudioEngine() {
        rows.forEach { row ->
            val actual = AuroraLight.lightsFor(row.ids.map { palettes.getValue(it) }, row.dark)
            val expected = mapOf(
                "l1" to row.l1, "l2" to row.l2, "l3" to row.l3,
                "k1" to row.k1, "k2" to row.k2, "k3" to row.k3,
                "tint" to row.tint, "bg" to row.bg,
            )
            assertEquals("${row.name} ${if (row.dark) "dark" else "light"}", expected, actual.hex())
        }
    }

    @Test
    fun hslRoundTripsLikeTheStudio() {
        // toHsl/toHex are exact inverses for 8-bit colours (Math.round semantics).
        listOf(0x000000, 0xffffff, 0xff7a3d, 0x2121de, 0x808080, 0x0b0620, 0xffe600, 0x7cc0e8).forEach { rgb ->
            val hsl = AuroraLight.toHsl(rgb)
            assertEquals(AuroraLight.hex(rgb), AuroraLight.hex(AuroraLight.toRgb(hsl.h, hsl.s, hsl.l)))
        }
        val metroidAccent = AuroraLight.toHsl(0xff7a3d)
        // node: toHsl('#ff7a3d') = [18.865979381443303, 1, 0.6196078431372549]
        assertEquals(18.865979381443303, metroidAccent.h, 1e-12)
        assertEquals(1.0, metroidAccent.s, 1e-12)
        assertEquals(0.6196078431372549, metroidAccent.l, 1e-12)
    }

    @Test
    fun yellowAccentBecomesTheThirdLight() {
        // Chrono Trigger's accent is yellow and the art has chroma elsewhere.
        val src = AuroraLight.sources(listOf(palettes.getValue("chrono")))
        assertEquals(AuroraLight.toHsl(0xffe066), src[2])
        // Super Metroid's ember accent leads.
        assertEquals(AuroraLight.toHsl(0xff7a3d), AuroraLight.sources(listOf(palettes.getValue("smetroid")))[0])
    }

    @Test
    fun paddingRepeatsTheLastGameWhenFewerThanThree() {
        val src = AuroraLight.sources(listOf(palettes.getValue("pacman"), palettes.getValue("neon")))
        assertEquals(3, src.size)
        assertEquals(src[1], src[2])
    }
