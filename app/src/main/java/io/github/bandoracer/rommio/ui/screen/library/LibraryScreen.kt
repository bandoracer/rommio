/** What the Library layouts can do. */
class LibraryActions(
    val openPlatform: (PlatformDto) -> Unit,
    val openCollection: (RommCollectionDto) -> Unit,
    val openGame: (romId: Int) -> Unit,
    /** Aurora's wall: its order and density (the model keeps them on this device). */
    val selectLens: (LibraryLens) -> Unit = {},
    val toggleColumns: () -> Unit = {},
)

/** A support tier's section title (docs/theme-layouts.md "Library"). */
fun tierTitle(tier: EmbeddedSupportTier): String = when (tier) {
    EmbeddedSupportTier.TOUCH_SUPPORTED -> "Touch-ready in app"
    EmbeddedSupportTier.CONTROLLER_SUPPORTED -> "Controller play in app"
    EmbeddedSupportTier.UNSUPPORTED -> "Not supported in app yet"
}

/** Riso's italic dek under a tier. */
fun tierDek(tier: EmbeddedSupportTier): String = when (tier) {
    EmbeddedSupportTier.TOUCH_SUPPORTED -> "Touch controls on screen; a controller works too."
    EmbeddedSupportTier.CONTROLLER_SUPPORTED -> "Playable here once a controller is connected."
    EmbeddedSupportTier.UNSUPPORTED -> "On your server, but no player on this device yet."
}

/** Collections grouped by kind, with their section titles. */
fun collectionSections(collections: List<RommCollectionDto>): List<Pair<String, List<RommCollectionDto>>> = listOf(
    "My collections" to collections.filter { it.kind == CollectionKind.REGULAR },
    "Smart collections" to collections.filter { it.kind == CollectionKind.SMART },
    "Autogenerated" to collections.filter { it.kind == CollectionKind.VIRTUAL },
).filter { it.second.isNotEmpty() }

/** What the regular-width detail column shows. */
private sealed interface LibrarySelection {
    data class Platform(val id: Int) : LibrarySelection
    data class Collection(val kind: CollectionKind, val id: String) : LibrarySelection
}

/**
 * Library (docs/theme-layouts.md "Library — two layouts"): platforms grouped by how they play,
 * and collections. Aurora sets every game on one wall of covers ordered by a lens; Riso sets a
 * contents page. On a regular width, platforms and collections sit in a narrow list beside the
 * selected one, on one shared background. The page is built by [LibraryViewModel] ([LibraryPage]).
 */
@Composable
fun LibraryScreen(
    container: AppContainer,
    imageBaseUrl: String?,
    onPlatformSelected: (PlatformDto) -> Unit,
    onOpenGame: (romId: Int) -> Unit,
    onCollectionSelected: (RommCollectionDto) -> Unit,
) {
    val context = LocalContext.current.applicationContext
    val viewModel: LibraryViewModel = viewModel(
        factory = viewModelFactory {
            initializer {
                LibraryViewModel(
                    container.repository,
                    container.playActivity,
                    container.savedProgress,
                    container.localPlay,
                    context.getSharedPreferences(LibraryViewModel.PREFERENCES, android.content.Context.MODE_PRIVATE),
                )
            }
        },
    )
    val page by viewModel.page.collectAsStateWithLifecycle()
    val actions = remember(viewModel, onPlatformSelected, onCollectionSelected, onOpenGame) {
        LibraryActions(
            openPlatform = onPlatformSelected,
            openCollection = onCollectionSelected,
            openGame = onOpenGame,
            selectLens = viewModel::selectLens,
            toggleColumns = viewModel::toggleColumns,
        )
    }
    if (isRegularWidth()) {
        LibrarySplit(container, imageBaseUrl, page, actions, onRefresh = viewModel::refresh)
        return
    }
    io.github.bandoracer.rommio.ui.component.RefreshBox(
        refreshing = page.isRefreshing,
        onRefresh = viewModel::refresh,
        modifier = Modifier.fillMaxSize(),
    ) {
        if (RommioTheme.isRiso) RisoLibraryLayout(page, actions) else AuroraLibraryLayout(page, actions)
    }
}

// ---- Regular width: a narrow list beside the selection ---------------------------------------

@Composable
private fun LibrarySplit(
    container: AppContainer,
    imageBaseUrl: String?,
    page: LibraryPage,
    actions: LibraryActions,
    onRefresh: () -> Unit,
) {
    val theme = RommioTheme.current
    var selectionKey by rememberSaveable { mutableStateOf<String?>(null) }
    val selection: LibrarySelection? = selectionKey?.let { key ->
        val parts = key.split(":", limit = 3)
        when (parts.firstOrNull()) {
            "p" -> parts.getOrNull(1)?.toIntOrNull()?.let { LibrarySelection.Platform(it) }
            "c" -> LibrarySelection.Collection(runCatching { CollectionKind.valueOf(parts[1]) }.getOrDefault(CollectionKind.REGULAR), parts.getOrElse(2) { "" })
            else -> null
        }
    } ?: page.sections.firstOrNull()?.platforms?.firstOrNull()?.let { LibrarySelection.Platform(it.platform.id) }

    Row(Modifier.fillMaxSize()) {
        io.github.bandoracer.rommio.ui.component.RefreshBox(
            refreshing = page.isRefreshing,
            onRefresh = onRefresh,
            modifier = Modifier.width(340.dp).fillMaxHeight(),
        ) {
            LazyColumn(
                Modifier.fillMaxSize().testTag("shell.libraryList"),
                contentPadding = PaddingValues(start = 20.dp, end = 12.dp, top = 8.dp, bottom = 32.dp),
            ) {
                // A column with `section` between its parts: each group is one item.
                item(key = "header", contentType = "header") { PageHeader(title = "Library") }
                val gap = Modifier.padding(top = theme.spacing.section)
                if (page.platforms.isEmpty() && page.collections.isEmpty()) {
                    item(key = "empty", contentType = "empty") {
                        EmptyState(
                            title = if (page.isLoading) "Loading your library" else "No platforms yet",
                            message = if (page.isLoading) "" else "Pull to refresh once your server is reachable.",
                            icon = Icons.Outlined.VideoLibrary,
                            modifier = gap,
                        )
                    }
                }
                page.sections.forEach { section ->
                    item(key = "tier/${section.tier}", contentType = "sidebarGroup") {
                        ListGroup(title = section.title, meta = section.platforms.size.toString(), modifier = gap) {
                            section.platforms.forEachIndexed { index, entry ->
                                if (index > 0 && !theme.isRiso) ListDivider()
                                val selected = selection == LibrarySelection.Platform(entry.platform.id)
                                SidebarRow(selected, onClick = { selectionKey = "p:${entry.platform.id}" }, tag = "library.platform.${entry.platform.slug}") {
                                    if (theme.isRiso) {
                                        ChapterRow(
                                            number = entry.number,
                                            platform = entry.platform,
                                            installed = entry.installed,
                                            compact = true,
                                            dimmed = section.tier == EmbeddedSupportTier.UNSUPPORTED,
                                        )
                                    } else {
                                        ListRow(title = entry.platform.name, subtitle = entry.shortSubtitle)
                                    }
                                }
                            }
                        }
                    }
                }
                page.collectionSections.forEach { (title, collections) ->
                    item(key = "collections/$title", contentType = "sidebarGroup") {
                        ListGroup(title = title, meta = collections.size.toString(), modifier = gap) {
                            collections.forEachIndexed { index, item ->
                                val collection = item.collection
                                if (index > 0 && !theme.isRiso) ListDivider()
                                val selected = selection == LibrarySelection.Collection(collection.kind, collection.id)
                                SidebarRow(selected, onClick = { selectionKey = "c:${collection.kind.name}:${collection.id}" }, tag = "library.collection.${collection.id}") {
                                    ListRow(title = collection.name, subtitle = item.countText)
                                }
                            }
                        }
                    }
                }
            }
        }
        Box(Modifier.weight(1f).fillMaxHeight()) {
            when (selection) {
                is LibrarySelection.Platform -> {
                    val platform = page.platforms.firstOrNull { it.platform.id == selection.id }?.platform
                    key(selection.id) {
                        PlatformScreen(
                            container = container,
                            platformId = selection.id,
                            platformName = platform?.name.orEmpty(),
                            imageBaseUrl = imageBaseUrl,
                            onOpenGame = actions.openGame,
                        )
                    }
                }
                is LibrarySelection.Collection -> {
                    val collection = page.collections.firstOrNull { it.collection.kind == selection.kind && it.collection.id == selection.id }?.collection
                    key(selection) {
                        CollectionDetailScreen(
                            container = container,
                            kind = selection.kind.name.lowercase(),
                            collectionId = selection.id,
                            collectionName = collection?.name.orEmpty(),
                            imageBaseUrl = imageBaseUrl,
                            onOpenGame = actions.openGame,
                        )
                    }
                }
                null -> EmptyState(title = "Choose a platform or collection", message = "", icon = Icons.Outlined.VideoLibrary, modifier = Modifier.fillMaxSize())
            }
        }
    }
}

/** A selectable sidebar row: the theme's pressed/selected fill behind it. */
@Composable
private fun SidebarRow(selected: Boolean, onClick: () -> Unit, tag: String, content: @Composable () -> Unit) {
    val theme = RommioTheme.current
    Box(
        Modifier
            .fillMaxWidth()
            .background(if (selected) (if (theme.isRiso) theme.colors.hairline else theme.colors.surfaceStrong) else androidx.compose.ui.graphics.Color.Transparent)
            .semantics { this.selected = selected }
            .clickable(role = Role.Tab, onClick = onClick)
            .testTag(tag),
    ) {
        content()
    }
}
