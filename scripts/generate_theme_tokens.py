def kotlin(doc: dict) -> str:
    fonts = doc["fonts"]
    color_roles = list(doc["colorRoles"])
    type_roles = list(doc["typeRoles"])
    ref = next(iter(doc["themes"].values()))
    player_roles = list(ref["player"]["light"])
    enums = shape_enums(doc)
    L: list[str] = []
    w = L.append
    w(f"// {HEADER}")
    w("package io.github.bandoracer.rommio.ui.theme")
    w("")
    w("import androidx.compose.ui.graphics.Color")
    w("import androidx.compose.ui.text.font.Font")
    w("import androidx.compose.ui.text.font.FontFamily")
    w("import androidx.compose.ui.text.font.FontStyle")
    w("import androidx.compose.ui.text.font.FontWeight")
    w("import io.github.bandoracer.rommio.R")
    w("")
    w("object RommioFontFamilies {")
    for key, font in fonts.items():
        w(f"    /** {font['family']} */")
        w(f"    val {pascal(key)}: FontFamily = FontFamily(")
        for face in font["faces"]:
            style = "FontStyle.Italic" if face.get("italic") else "FontStyle.Normal"
            w(f"        Font(R.font.{face['file']}, FontWeight({face['weight']}), {style}),")
        w("    )")
    w("")
    w("    fun byKey(key: String): FontFamily = when (key) {")
    for key in fonts:
        w(f"        \"{key}\" -> {pascal(key)}")
    w("        else -> FontFamily.Default")
    w("    }")
    w("}")
    w("")
    for name, values in enums.items():
        w(f"enum class Player{pascal(name)}Style {{ {', '.join(camel_to_const(v) for v in values)} }}")
    w("")
    w("data class ThemeColorTokens(")
    for role in color_roles:
        w(f"    /** {doc['colorRoles'][role]} */")
        w(f"    val {role}: Color,")
    w(")")
    w("")
    w("data class TypeRoleToken(")
    w("    val fontKey: String,")
    w("    val weight: Int,")
    w("    val italic: Boolean,")
    w("    /** sp */")
    w("    val size: Float,")
    w("    /** multiple of size */")
    w("    val lineHeight: Float,")
    w("    /** em */")
    w("    val tracking: Float,")
    w("    val uppercase: Boolean,")
    w("    val tabular: Boolean,")
    w(") {")
    w("    val family: FontFamily get() = RommioFontFamilies.byKey(fontKey)")
    w("    val fontWeight: FontWeight get() = FontWeight(weight)")
    w("    val fontStyle: FontStyle get() = if (italic) FontStyle.Italic else FontStyle.Normal")
    w("}")
    w("")
    w("data class ThemeTypeTokens(")
    for role in type_roles:
        w(f"    /** {doc['typeRoles'][role]} */")
        w(f"    val {role}: TypeRoleToken,")
    w(")")
    w("")
    for block in ("radius", "spacing", "material"):
        w(f"data class Theme{pascal(block)}Tokens(")
        for k, v in ref[block].items():
            kt = "Boolean" if isinstance(v, bool) else "Float"
            w(f"    val {k}: {kt},")
        w(")")
        w("")
    w("data class PlayerColorTokens(")
    for role in player_roles:
        w(f"    val {role}: Color,")
    w(")")
    w("")
    w("data class PlayerShapeTokens(")
    for k, v in ref["player"]["shape"].items():
        if isinstance(v, str):
            w(f"    val {k}: Player{pascal(k)}Style,")
        elif isinstance(v, bool):
            w(f"    val {k}: Boolean,")
        else:
            w(f"    val {k}: Float,")
    w(")")
    w("")
    w("data class ThemeTokenSet(")
    w("    val key: String,")
    w("    val name: String,")
    w("    val summary: String,")
    w("    val light: ThemeColorTokens,")
    w("    val dark: ThemeColorTokens,")
    w("    val type: ThemeTypeTokens,")
    w("    val radius: ThemeRadiusTokens,")
    w("    val spacing: ThemeSpacingTokens,")
    w("    val material: ThemeMaterialTokens,")
    w("    val playerLight: PlayerColorTokens,")
    w("    val playerDark: PlayerColorTokens,")
    w("    val playerShape: PlayerShapeTokens,")
    w(") {")
    w("    fun colors(dark: Boolean): ThemeColorTokens = if (dark) this.dark else light")
    w("    fun player(dark: Boolean): PlayerColorTokens = if (dark) playerDark else playerLight")
    w("}")
    w("")

    def kcolor(v: str) -> str:
        r, g, b, a = rgba(v)
        return f"Color(0x{round(a * 255):02X}{r:02X}{g:02X}{b:02X})"

    def kval(v) -> str:
        if isinstance(v, bool):
            return "true" if v else "false"
        return f"{num(v)}f"

    w("object ThemeTokens {")
    for key, theme in doc["themes"].items():
        w(f"    val {pascal(key)}: ThemeTokenSet = ThemeTokenSet(")
        w(f"        key = \"{key}\",")
        w(f"        name = \"{theme['name']}\",")
        w(f"        summary = \"{theme['summary']}\",")
        for scheme in ("light", "dark"):
            w(f"        {scheme} = ThemeColorTokens(")
            for role in color_roles:
                w(f"            {role} = {kcolor(theme['colors'][scheme][role])},")
            w("        ),")
        w("        type = ThemeTypeTokens(")
        for role in type_roles:
            s = theme["type"][role]
            w(
                f"            {role} = TypeRoleToken(\"{s['font']}\", {s['weight']}, {kval(s.get('italic', False))}, "
                f"{kval(s['size'])}, {kval(s['lineHeight'])}, {kval(s['tracking'])}, "
                f"{kval(s.get('uppercase', False))}, {kval(s.get('tabular', False))}),"
            )
        w("        ),")
        for block in ("radius", "spacing", "material"):
            args = ", ".join(f"{k} = {kval(v)}" for k, v in theme[block].items())
            w(f"        {block} = Theme{pascal(block)}Tokens({args}),")
        for scheme in ("light", "dark"):
            w(f"        player{pascal(scheme)} = PlayerColorTokens(")
            for role in player_roles:
                w(f"            {role} = {kcolor(theme['player'][scheme][role])},")
            w("        ),")
        parts = []
        for k, v in theme["player"]["shape"].items():
            parts.append(f"{k} = Player{pascal(k)}Style.{camel_to_const(v)}" if isinstance(v, str) else f"{k} = {kval(v)}")
        w("        playerShape = PlayerShapeTokens(")
        for p in parts:
            w(f"            {p},")
        w("        ),")
        w("    )")
        w("")
    w("    val all: List<ThemeTokenSet> = listOf(" + ", ".join(pascal(k) for k in doc["themes"]) + ")")
    w("")
    w("    fun forKey(key: String): ThemeTokenSet = all.firstOrNull { it.key == key } ?: " + pascal(next(iter(doc["themes"]))))
    w("}")
    w("")
    w(kotlin_art(doc))
    return "\n".join(L)


