#!/usr/bin/env python3
"""Generate the Aurora/Riso theme token code for Android and iOS.

Reads design/tokens/themes.json and writes:
  app/src/main/java/io/github/bandoracer/rommio/ui/theme/ThemeTokens.kt
  ios/Sources/RommioUI/Theme/ThemeTokens.swift

Run from the repo root:
  python3 scripts/generate_theme_tokens.py          # write both files
  python3 scripts/generate_theme_tokens.py --check  # fail if either file is stale
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "design/tokens/themes.json"
KOTLIN_OUT = ROOT / "app/src/main/java/io/github/bandoracer/rommio/ui/theme/ThemeTokens.kt"
SWIFT_OUT = ROOT / "ios/Sources/RommioUI/Theme/ThemeTokens.swift"
HEADER = "Generated by scripts/generate_theme_tokens.py from design/tokens/themes.json. Do not edit."


def rgba(value: str) -> tuple[int, int, int, float]:
    m = re.fullmatch(r"#([0-9a-fA-F]{6})(?:/([0-9.]+))?", value)
    if not m:
        raise SystemExit(f"bad colour {value!r}")
    h = m.group(1)
    alpha = float(m.group(2)) if m.group(2) else 1.0
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), alpha


def num(x: float) -> str:
    s = f"{float(x):.4f}".rstrip("0").rstrip(".")
    return s if s not in ("", "-0") else "0"


def camel_to_const(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).upper()


def pascal(name: str) -> str:
    return name[0].upper() + name[1:]


def validate(doc: dict) -> None:
    color_roles = list(doc["colorRoles"])
    type_roles = list(doc["typeRoles"])
    themes = doc["themes"]
    ref = next(iter(themes.values()))
    for key, theme in themes.items():
        for scheme in ("light", "dark"):
            got = list(theme["colors"][scheme])
            if sorted(got) != sorted(color_roles):
                raise SystemExit(f"{key}.{scheme}: colour roles {sorted(set(got) ^ set(color_roles))} mismatch")
            if sorted(theme["player"][scheme]) != sorted(ref["player"][scheme]):
                raise SystemExit(f"{key}.player.{scheme}: roles differ from {next(iter(themes))}")
        if sorted(theme["type"]) != sorted(type_roles):
            raise SystemExit(f"{key}: type roles {sorted(set(theme['type']) ^ set(type_roles))} mismatch")
        for block in ("radius", "spacing", "material"):
            if sorted(theme[block]) != sorted(ref[block]):
                raise SystemExit(f"{key}.{block}: keys differ from {next(iter(themes))}")
        if sorted(theme["player"]["shape"]) != sorted(ref["player"]["shape"]):
            raise SystemExit(f"{key}.player.shape: keys differ")
        for role, spec in theme["type"].items():
            faces = doc["fonts"][spec["font"]]["faces"]
            if not any(f["weight"] == spec["weight"] and f.get("italic", False) == spec.get("italic", False) for f in faces):
                raise SystemExit(f"{key}.type.{role}: no {spec['font']} face at weight {spec['weight']}")


def shape_enums(doc: dict) -> dict[str, list[str]]:
    out: dict[str, list[str]] = {}
    for theme in doc["themes"].values():
        for k, v in theme["player"]["shape"].items():
            if isinstance(v, str):
                out.setdefault(k, [])
                if v not in out[k]:
                    out[k].append(v)
    return out


